#define DB_N (int)(sizeof(DB) / sizeof(DB[0]))

static const char *emo_name(int e) {
    return e == EMO_LOST ? "失落" : e == EMO_HAPPY ? "开心" : "平静";
}

static void run(int screen_w, int font_px) {
    int i, fail = 0;
    printf("\n===== screen_w=%d  font=%dpx  line=%.1f =====\n",
           screen_w, font_px, (double)BUB_LINE_RATIO);
    printf("%-4s %-4s %6s %6s %6s %6s %5s %6s %6s %s\n",
           "档", "#", "strlen", "字数", "宽", "高", "封顶", "行数", "需高", "判定");
    for (i = 0; i < DB_N; i++) {
        ChatBubble_t b;
        int need_h = 0, lines, avail_h;
        size_t blen = strlen(DB[i].text);
        b.text_content = (char *)DB[i].text;
        b.emotion_type = DB[i].emo;
        RenderBubble(&b, screen_w);
        lines = bubble_wrap_lines(&b, font_px, &need_h);
        avail_h = (int)(b.bubble_height * BUB_TEXT_H_RATIO);
        printf("%-4s %-4d %6u %6d %6d %6d %5s %6d %6d %s\n",
               DB[i].tier, i + 1, (unsigned)blen, b.char_length,
               b.bubble_width, b.bubble_height,
               bubble_tail_stretch(&b) ? "是" : "-",
               lines, need_h,
               need_h <= avail_h ? "OK" : "会切字");
        if (need_h > avail_h)
            fail++;
        /* 断言：字符数必须小于等于字节数，且中文台词严格小于 */
        if (b.char_length > (int)blen) {
            printf("  !! charlen > strlen，UTF-8 计数逻辑错了\n");
            fail++;
        }
        /* 断言：宽度不得超过上限 */
        {
            int cap = BUB_MAX_W;
            int s80 = (int)(screen_w * BUB_SCREEN_CAP);
            if (screen_w > 0 && s80 < cap) cap = s80;
            if (b.bubble_width > cap) {
                printf("  !! 宽度 %d 超过上限 %d\n", b.bubble_width, cap);
                fail++;
            }
        }
    }
    printf("---- %s (fail=%d) ----\n", fail ? "FAIL" : "PASS", fail);
}

int main(void) {
    SetConsoleOutputCP(65001);

    /* 规格 [FIX-1] 的直接证据：同一条台词 strlen vs 字数 */
    printf("[FIX-1] strlen 数字节，中文 UTF-8 一字 3 字节：\n");
    printf("  \"%s\"\n", DB[0].text);
    printf("  strlen = %u  ->  规格公式宽 = %d\n",
           (unsigned)strlen(DB[0].text),
           BUB_BASE_W + (int)strlen(DB[0].text) * BUB_W_PER_CHAR);
    printf("  字数   = %d  ->  正确公式宽 = %d\n",
           bubble_charlen(DB[0].text),
           BUB_BASE_W + bubble_charlen(DB[0].text) * BUB_W_PER_CHAR);

    run(1920, BUB_FONT_PX);   /* 600 上限生效 */
    run(800, BUB_FONT_PX);     /* 800*0.8=640 > 600，仍是 600 生效 */
    run(640, BUB_FONT_PX);     /* 640*0.8=512 < 600，屏宽 80% 生效 */
    return 0;
}
